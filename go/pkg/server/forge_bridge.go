// probeForgeAuth performs a direct net/http call to /api/v1/user with the
// token in the Authorization: Bearer header. Mirrors what go-forge does
// internally so a probe failure here implies a real auth problem (not a
// go-forge wiring quirk). Returns the authenticated user's login on
// success.
func probeForgeAuth(ctx context.Context, base, token string) (string, error) {
	c, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	req, err := http.NewRequestWithContext(c, http.MethodGet, base+"/api/v1/user", nil)
	if err != nil {
		return "", err
	}
	req.Header.Set("Authorization", "Bearer "+token)
	req.Header.Set("Accept", "application/json")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return "", err
	}
	defer func() { _ = resp.Body.Close() }()
	body, _ := io.ReadAll(resp.Body)
	if resp.StatusCode >= 400 {
		return "", fmt.Errorf("HTTP %d: %s", resp.StatusCode, strings.TrimSpace(string(body)))
	}
	var user struct {
		Login string `json:"login"`
	}
	if err := json.Unmarshal(body, &user); err != nil {
		return "", err
	}
	return user.Login, nil
}

// forge_* bridge tools surface the canonical core/go-forge Forgejo client.
// Token resolution: ~/.claude/secrets/forge_token (single-line) | env
// FORGE_TOKEN | core config "forge.token". Base URL: env FORGE_URL or
// "https://forge.lthn.sh" (Snider's homelab — adjust per machine).

var (
	forgeOnce   sync.Once
	forgeClient *forge.Forge
	forgeBase   string
	forgeOk     bool
)

func (b *MCPBridge) forgeService() (*forge.Forge, bool) {
	forgeOnce.Do(func() {
		token := readForgeToken()
		if strings.TrimSpace(token) == "" {
			return
		}
		base := os.Getenv("FORGE_URL")
		if base == "" {
			base = "https://forge.lthn.sh"
		}
		forgeBase = base
		forgeClient = forge.NewForge(base, token)
		forgeOk = true
		// Light diagnostic so the dev sees the token-source + length without
		// printing the secret. Useful when 401s happen and the user wonders
		// which path won the resolver. Prefix only — never log the full
		// token. Sha1 prefix lets a developer cross-check against forgejo's
		// "access token does not exist [sha: …]" error message.
		prefix := token
		if len(prefix) > 6 {
			prefix = prefix[:6]
		}
		sum := sha1.Sum([]byte(token))
		hash := hex.EncodeToString(sum[:])
		core.Print(core.Stderr(), "ide.server.forge: base=%s token_len=%d prefix=%s sha1=%s\n", base, len(token), prefix, hash)
	})
	return forgeClient, forgeOk
}

func readForgeToken() string {
	if t := strings.TrimSpace(os.Getenv("FORGE_TOKEN")); t != "" {
		return t
	}
	home, err := os.UserHomeDir()
	if err == nil {
		paths := []string{
			filepath.Join(home, ".claude", "secrets", "forge_token"),
			filepath.Join(home, ".core", "secrets", "forge_token"),
		}
		for _, p := range paths {
			data, err := os.ReadFile(p)
			if err == nil {
				// Strip ALL whitespace including embedded \r and \n the
				// file might contain when generated by tools that wrap
				// the token across lines.
				out := strings.Map(func(r rune) rune {
					switch r {
					case ' ', '\t', '\n', '\r', 0:
						return -1
					}
					return r
				}, string(data))
				if out != "" {
					return out
				}
			}
		}
	}
	return ""
}

// toolForgeStatus reports whether a forge client could be initialised + the
// resolved base URL. Probes /api/v1/user with the loaded token via net/http
// directly so the panel surfaces a clean "configured & valid" vs "configured
// but rejected" distinction (the latter usually means an expired/revoked
// token).
func (b *MCPBridge) toolForgeStatus(ctx context.Context, _ map[string]any) map[string]any {
	_, ok := b.forgeService()
	hint := ""
	authed := false
	authedAs := ""
	if !ok {
		hint = "no token found — set FORGE_TOKEN env, or write a token to ~/.claude/secrets/forge_token"
	} else {
		token := readForgeToken()
		// Direct probe via net/http with both header forms (Forgejo accepts
		// either; we use Bearer to match go-forge's emit shape).
		login, err := probeForgeAuth(ctx, forgeBase, token)
		if err == nil && login != "" {
			authed = true
			authedAs = login
		} else if err != nil {
			hint = "token rejected by " + forgeBase + ": " + err.Error()
		}
	}
	return map[string]any{
		"ok": true,
		"value": map[string]any{
			"configured":   ok,
			"authenticated": authed,
			"as":           authedAs,
			"base":         forgeBase,
			"hint":         hint,
		},
	}
}

// toolForgeOrgs lists orgs the authenticated user belongs to. Snider's
// account spans `core` (homelab canon), `lthn` (network), `agent` etc.
func (b *MCPBridge) toolForgeOrgs(ctx context.Context, _ map[string]any) map[string]any {
	f, ok := b.forgeService()
	if !ok {
		return errResp("forge client not configured")
	}
	orgs, err := f.Orgs.ListOrgs(ctx)
	if err != nil {
		return map[string]any{"ok": false, "error": err.Error()}
	}
	out := make([]map[string]any, 0, len(orgs))
	for _, o := range orgs {
		out = append(out, map[string]any{
			"name":        o.Name,
			"full_name":   o.FullName,
			"description": o.Description,
			"website":     o.Website,
			"avatar":      o.AvatarURL,
		})
	}
	return map[string]any{"ok": true, "value": map[string]any{"orgs": out, "count": len(out)}}
}

// toolForgeRepos lists repos for an org (or the authenticated user when
// org is empty). Returns name/full_name/description/private/fork/stars.
func (b *MCPBridge) toolForgeRepos(ctx context.Context, params map[string]any) map[string]any {
	f, ok := b.forgeService()
	if !ok {
		return errResp("forge client not configured")
	}
	org := paramString(params, "org", "")
	var repos []forgeRepo
	if org == "" {
		raw, err := f.Repos.ListUserRepos(ctx)
		if err != nil {
			return map[string]any{"ok": false, "error": err.Error()}
		}
		for _, r := range raw {
			repos = append(repos, repoToInfo(r))
		}
	} else {
		raw, err := f.Repos.ListOrgRepos(ctx, org)
		if err != nil {
			return map[string]any{"ok": false, "error": err.Error()}
		}
		for _, r := range raw {
			repos = append(repos, repoToInfo(r))
		}
	}
	out := make([]map[string]any, 0, len(repos))
	for _, r := range repos {
		out = append(out, map[string]any{
			"name":        r.Name,
			"full_name":   r.FullName,
			"description": r.Description,
			"private":     r.Private,
			"fork":        r.Fork,
			"stars":       r.Stars,
			"updated_at":  r.UpdatedAt,
			"html_url":    r.HTMLURL,
		})
	}
	return map[string]any{"ok": true, "value": map[string]any{"repos": out, "count": len(out)}}
}

// toolForgeIssues lists issues for a given owner/repo. State filter
// optional ("open" | "closed" | "all" — default "open").
func (b *MCPBridge) toolForgeIssues(ctx context.Context, params map[string]any) map[string]any {
	f, ok := b.forgeService()
	if !ok {
		return errResp("forge client not configured")
	}
	owner := paramString(params, "owner", "")
	repo := paramString(params, "repo", "")
	if owner == "" || repo == "" {
		return errResp("owner + repo required")
	}
	issues, err := f.Issues.ListRepoIssues(ctx, owner, repo)
	if err != nil {
		return map[string]any{"ok": false, "error": err.Error()}
	}
	out := make([]map[string]any, 0, len(issues))
	for _, i := range issues {
		// PR-shaped issues have PullRequest field set; skip those (covered
		// by toolForgePulls)
		if i.PullRequest != nil {
			continue
		}
		out = append(out, map[string]any{
			"number":     i.Index,
			"title":      i.Title,
			"state":      i.State,
			"comments":   i.Comments,
			"updated_at": i.Updated,
			"html_url":   i.HTMLURL,
			"author":     userLogin(i.User),
		})
	}
	return map[string]any{"ok": true, "value": map[string]any{"issues": out, "count": len(out)}}
}

// toolForgePulls lists PRs for a repo.
