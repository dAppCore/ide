// toolForgeReleases lists recent releases AND tags for a single owner/repo.
// Forge.lthn.sh repos commonly use tags without an explicit GitHub-style
// "release" — so we surface both, merged + sorted by recency. Calls the
// API directly (go-forge's Releases service exists but no TagService yet).
func (b *MCPBridge) toolForgeReleases(ctx context.Context, params map[string]any) map[string]any {
	owner := strings.TrimSpace(paramString(params, "owner", ""))
	repo := strings.TrimSpace(paramString(params, "repo", ""))
	if owner == "" || repo == "" {
		return map[string]any{"ok": false, "error": "owner and repo required"}
	}
	limit := paramInt(params, "limit", 20)
	if limit <= 0 || limit > 100 {
		limit = 20
	}

	out := make([]map[string]any, 0, limit)

	// Try Releases first (explicit releases trump tags when present)
	if f, ok := b.forgeService(); ok {
		page, err := f.Releases.ListReleasesPage(ctx, owner, repo, forge.ListOptions{Page: 1, PageSize: limit})
		if err == nil {
			for _, r := range page.Items {
				out = append(out, map[string]any{
					"kind":         "release",
					"name":         r.TagName,
					"title":        r.Title,
					"target":       r.Target,
					"draft":        r.IsDraft,
					"prerelease":   r.IsPrerelease,
					"published_at": r.PublishedAt.UTC().Format(time.RFC3339),
					"html_url":     r.HTMLURL,
					"tarball_url":  r.TarURL,
					"author":       userLogin(r.Author),
				})
			}
		}
	}

	// Always merge in tags too — Forge repos often only have tags.
	tagURL := strings.TrimSuffix(forgeBaseURL(), "/") + "/api/v1/repos/" + owner + "/" + repo + "/tags?limit=" + fmt.Sprintf("%d", limit)
	if tagBody := forgeAuthedGET(tagURL); tagBody != nil {
		var tags []struct {
			Name        string `json:"name"`
			Message     string `json:"message"`
			ID          string `json:"id"`
			ZipballURL  string `json:"zipball_url"`
			TarballURL  string `json:"tarball_url"`
			Commit      struct {
				URL     string `json:"url"`
				SHA     string `json:"sha"`
				Created string `json:"created"`
			} `json:"commit"`
		}
		if err := json.Unmarshal(tagBody, &tags); err == nil {
			seen := map[string]bool{}
			for _, e := range out {
				seen[asString(e["name"])] = true
			}
			for _, t := range tags {
				if seen[t.Name] {
					continue
				}
				out = append(out, map[string]any{
					"kind":         "tag",
					"name":         t.Name,
					"title":        t.Message,
					"target":       t.Commit.SHA,
					"published_at": t.Commit.Created,
					"tarball_url":  t.TarballURL,
					"zipball_url":  t.ZipballURL,
					"html_url":     "https://forge.lthn.sh/" + owner + "/" + repo + "/src/tag/" + t.Name,
				})
			}
		}
	}

	// Sort by published_at desc; cap to limit
	sort.Slice(out, func(i, j int) bool {
		return asString(out[i]["published_at"]) > asString(out[j]["published_at"])
	})
	if len(out) > limit {
		out = out[:limit]
	}

	return map[string]any{
		"ok": true,
		"value": map[string]any{
			"releases": out,
			"count":    len(out),
			"owner":    owner,
			"repo":     repo,
		},
	}
}

func forgeBaseURL() string {
	if v := strings.TrimSpace(os.Getenv("FORGE_URL")); v != "" {
		return v
	}
	return "https://forge.lthn.sh"
}

func forgeAuthedGET(url string) []byte {
	tok := readForgeToken()
	if tok == "" {
		return nil
	}
	req, err := http.NewRequest(http.MethodGet, url, nil)
	if err != nil {
		return nil
	}
	req.Header.Set("Authorization", "token "+tok)
	req.Header.Set("Accept", "application/json")
	resp, err := (&http.Client{Timeout: 10 * time.Second}).Do(req)
	if err != nil {
		return nil
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode >= 400 {
		return nil
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil
	}
	return body
}

// toolForgeNotifications lists the authenticated user's pending forge
// notifications (mentions, reviews requested, issue assignments, etc).
func (b *MCPBridge) toolForgeNotifications(ctx context.Context, _ map[string]any) map[string]any {
	f, ok := b.forgeService()
	if !ok {
		return errResp("forge client not configured")
	}
	notes, err := f.Notifications.List(ctx)
	if err != nil {
		return map[string]any{"ok": false, "error": err.Error()}
	}
	out := make([]map[string]any, 0, len(notes))
	for _, n := range notes {
		entry := map[string]any{
			"id":         n.ID,
			"unread":     n.Unread,
			"pinned":     n.Pinned,
			"updated_at": n.UpdatedAt,
		}
		if n.Subject != nil {
			entry["title"] = n.Subject.Title
			entry["type"] = n.Subject.Type
			entry["url"] = n.Subject.HTMLURL
			entry["state"] = n.Subject.State
		}
		if n.Repository != nil {
			entry["repo"] = n.Repository.FullName
		}
		out = append(out, entry)
	}
	return map[string]any{"ok": true, "value": map[string]any{"notifications": out, "count": len(out)}}
}

type forgeRepo struct {
	Name, FullName, Description, HTMLURL string
	Private, Fork                         bool
	Stars                                 int64
	UpdatedAt                             string
}

func repoToInfo(r interface{}) forgeRepo {
	// types.Repository is bound at compile time; reflective coercion via
	// JSON keeps this file decoupled from the autogen types package.
	out := forgeRepo{}
	data := core.JSONMarshalString(r)
	parsed := map[string]any{}
	core.JSONUnmarshalString(data, &parsed)
	out.Name = stringOrEmpty(parsed["name"])
	out.FullName = stringOrEmpty(parsed["full_name"])
	out.Description = stringOrEmpty(parsed["description"])
	out.HTMLURL = stringOrEmpty(parsed["html_url"])
	out.Private = boolOrFalse(parsed["private"])
	out.Fork = boolOrFalse(parsed["fork"])
	if v, ok := parsed["stars_count"].(float64); ok {
		out.Stars = int64(v)
	}
	out.UpdatedAt = stringOrEmpty(parsed["updated_at"])
	return out
}

func stringOrEmpty(v any) string {
	if s, ok := v.(string); ok {
		return s
	}
	return ""
}

func boolOrFalse(v any) bool {
	if b, ok := v.(bool); ok {
		return b
	}
	return false
}

func userLogin(u any) string {
	if u == nil {
		return ""
	}
	data := core.JSONMarshalString(u)
	parsed := map[string]any{}
	core.JSONUnmarshalString(data, &parsed)
	return stringOrEmpty(parsed["login"])
}
